-- 1. יצירה או עדכון של טבלת השיעורים והסרטונים (lessons) עם כל העמודות הנדרשות
CREATE TABLE IF NOT EXISTS public.lessons (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp with time zone DEFAULT timezone('utc'::text, now()) NOT NULL,
    title text NOT NULL,
    description text DEFAULT ''::text,
    video_url text DEFAULT ''::text,
    category text DEFAULT 'כללי'::text,
    topic text DEFAULT 'כללי'::text,
    rabbi_name text DEFAULT 'בית המדרש צדיק-טוק'::text,
    rabbi text DEFAULT 'בית המדרש צדיק-טוק'::text,
    institution text DEFAULT 'בית המדרש'::text,
    duration text DEFAULT 'וידאו'::text,
    user_id uuid DEFAULT auth.uid(),
    is_approved boolean DEFAULT false NOT NULL
);

