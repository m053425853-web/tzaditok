ON public.lessons
FOR SELECT
TO anon, authenticated
USING (true);

-- ב. הוספת תוכן (INSERT): מאפשרת למשתמשים מחוברים (וגם לאורחים בטופס ההעלאה) לשלוח סרטון/שיעור חדש
CREATE POLICY "lessons_insert_authenticated"
ON public.lessons
FOR INSERT
TO anon, authenticated
WITH CHECK (true);

-- ג. אישור/עדכון תוכן (UPDATE): מותר אך ורק למנהל המערכת m053425853@gmail.com
