-- הסרת פוליסות ישנות שעלולות לחסום INSERT או SELECT
DROP POLICY IF EXISTS "lessons_select_all" ON public.lessons;
DROP POLICY IF EXISTS "lessons_insert_pending" ON public.lessons;
DROP POLICY IF EXISTS "lessons_insert_authenticated" ON public.lessons;
DROP POLICY IF EXISTS "lessons_admin_update" ON public.lessons;
DROP POLICY IF EXISTS "lessons_admin_delete" ON public.lessons;
DROP POLICY IF EXISTS "Public read lessons" ON public.lessons;
DROP POLICY IF EXISTS "Authenticated insert lessons" ON public.lessons;
DROP POLICY IF EXISTS "Anyone can read lessons" ON public.lessons;
DROP POLICY IF EXISTS "Anyone can insert lessons" ON public.lessons;

-- א. קריאה (SELECT): פתוחה לכולם כדי שהאתר ופאנל הניהול יוכלו לשלוף שיעורים ותכנים
